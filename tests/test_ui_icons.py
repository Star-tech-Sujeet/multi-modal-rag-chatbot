"""
Focused regression tests for Aura AI UI local SVG/PNG asset resolution and rendering.

Verifies:
1. Robust local asset discovery for all 7 required UI assets.
2. In-memory data URI generation and zero-redundant disk caching.
3. CSS rules injection for UI icon classes and pseudo-elements.
4. Absence of functional emojis in empty-state prompts, expander labels, and topbar pills.
"""

from pathlib import Path
from unittest.mock import patch, MagicMock
import pytest

from ui.streamlit_app import (
    resolve_ui_asset_path,
    get_ui_asset_data_uri,
    get_aura_symbol_data_uri,
    AURA_AI_SYMBOL,
    AURA_AI_SYMBOL_FILENAME,
    _UI_ASSET_DATA_URI_CACHE,
    apply_custom_styles,
    SUGGESTION_ICONS,
)


EXPECTED_ASSETS = [
    "upload.svg",
    "documents-folder.svg",
    "innovation.svg",
    "swap.svg",
    "find.png",
    "icons8-rename-48.svg",
    "icons8-trash-24.svg",
    "comment-alt-medical.svg",
]


class TestUIIconAssetResolution:
    """Verifies resolution and caching of local SVG and PNG UI assets."""

    def test_all_assets_resolve_successfully(self):
        """Verify each of the 8 required icon assets exists and resolves to a Path."""
        for filename in EXPECTED_ASSETS:
            path = resolve_ui_asset_path(filename)
            assert path is not None, f"Failed to resolve UI asset: {filename}"
            assert path.exists(), f"Asset path does not exist on disk: {path}"
            assert path.is_file(), f"Asset path is not a file: {path}"
            assert path.name == filename

    def test_nonexistent_asset_returns_none(self):
        """Verify non-existent asset returns None gracefully without error."""
        resolved = resolve_ui_asset_path("non_existent_icon.svg")
        assert resolved is None

    def test_data_uri_generation_and_caching(self):
        """Verify data URI generation with proper MIME types and in-memory cache hit."""
        for filename in EXPECTED_ASSETS:
            uri1 = get_ui_asset_data_uri(filename)
            assert uri1 != "", f"Empty data URI generated for {filename}"
            if filename.endswith(".svg"):
                assert uri1.startswith("data:image/svg+xml;base64,")
            elif filename.endswith(".png"):
                assert uri1.startswith("data:image/png;base64,")
            
            # Second call must return cached result
            uri2 = get_ui_asset_data_uri(filename)
            assert uri1 == uri2
            assert filename in _UI_ASSET_DATA_URI_CACHE


