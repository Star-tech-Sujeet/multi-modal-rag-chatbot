class TestSuggestionIconsMapping:
    """Verifies that suggestion buttons have explicit, distinct, and correct icon mappings."""

    def test_explicit_suggestion_icons_mapping(self):
        """Verify the exact required icon mapping in SUGGESTION_ICONS."""
        assert SUGGESTION_ICONS["Summarize this document"] == "ui/assets/documents-folder.svg"
        assert SUGGESTION_ICONS["Explain key concepts"] == "ui/assets/innovation.svg"
        assert SUGGESTION_ICONS["Find critical facts"] == "ui/assets/find.png"
        assert SUGGESTION_ICONS["Compare documents"] == "ui/assets/swap.svg"
        assert SUGGESTION_ICONS["Attach Image / Chart (Optional)"] == "ui/assets/upload.svg"

    def test_each_suggestion_has_unique_distinct_asset(self):
        """Ensure no two suggestion actions accidentally share the same icon asset."""
        mapped_assets = [
            SUGGESTION_ICONS["Summarize this document"],
            SUGGESTION_ICONS["Explain key concepts"],
            SUGGESTION_ICONS["Find critical facts"],
            SUGGESTION_ICONS["Compare documents"],
            SUGGESTION_ICONS["Attach Image / Chart (Optional)"],
        ]
        assert len(mapped_assets) == len(set(mapped_assets)), "Found duplicate assets in SUGGESTION_ICONS"

        # Verify find.png is strictly PNG and swap.svg is strictly swap
        assert SUGGESTION_ICONS["Find critical facts"].endswith(".png")
        assert "documents-folder" not in SUGGESTION_ICONS["Find critical facts"]
        assert "documents-folder" not in SUGGESTION_ICONS["Compare documents"]
        assert "documents-folder" not in SUGGESTION_ICONS["Explain key concepts"]

    def test_css_rules_bind_distinct_assets_to_each_suggestion_button(self):
        """Verify CSS generated by apply_custom_styles binds each distinct asset URI to its button."""
        from streamlit.testing.v1 import AppTest
        app_path = (Path(__file__).parent.parent / "ui" / "streamlit_app.py").resolve()
        at = AppTest.from_file(str(app_path), default_timeout=30)
        at.run()

        style_blocks = [m.value for m in at.markdown if "aura-hero-btn-container" in m.value or "st-key-hero_prompt_0" in m.value]
        assert len(style_blocks) > 0, "Hero button style rules not found in rendered app"
        css = style_blocks[0]

        doc_folder_uri = get_ui_asset_data_uri("documents-folder.svg")
        innovation_uri = get_ui_asset_data_uri("innovation.svg")
        find_uri = get_ui_asset_data_uri("find.png")
        swap_uri = get_ui_asset_data_uri("swap.svg")

        # Verify each button key has its specific asset URI bound
        assert ".st-key-hero_prompt_0 button" in css
        assert ".st-key-hero_prompt_1 button" in css
        assert ".st-key-hero_prompt_2 button" in css
        assert ".st-key-hero_prompt_3 button" in css

        # Verify URIs are present and have correct MIME types
        assert find_uri.startswith("data:image/png;base64,")
        assert doc_folder_uri.startswith("data:image/svg+xml;base64,")
        assert swap_uri.startswith("data:image/svg+xml;base64,")
        assert innovation_uri.startswith("data:image/svg+xml;base64,")

        # Verify distinctness: no 2 URIs are the same
        uris = [doc_folder_uri, innovation_uri, find_uri, swap_uri]
        assert len(uris) == len(set(uris)), "Expected all 4 suggestion button URIs to be unique"


